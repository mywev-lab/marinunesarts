/** Primeira parte do endereço em português → em inglês */
const SEGMENTS_EN: Record<string, string> = {
  produtos: 'shop',
  obras: 'works',
  sobre: 'about',
  contato: 'contact',
  privacidade: 'privacy',
}

/** Endereço do site (em português) → endereço no idioma pedido. Links externos ficam como estão. */
export function localizePath(href: string, locale: Locale): string {
  if (locale === 'pt' || !href || !href.startsWith('/') || href.startsWith('//')) return href
  if (href === '/en' || /^\/en[/?#]/.test(href)) return href
  const m = href.match(/^([^?#]*)(.*)$/)!
  const [first, ...rest] = m[1].split('/').filter(Boolean)
  if (!first) return `/en${m[2]}`
  // painel e API não têm versão em inglês
  if (first === 'admin' || first === 'api' || first.includes('.')) return href
  return `/en/${[SEGMENTS_EN[first] || first, ...rest].join('/')}${m[2]}`
}

/** Endereços da mesma página nos dois idiomas (para o seletor PT/EN e o Google) */
export const alternatePaths = (path: string): Record<Locale, string> => ({ pt: path, en: localizePath(path, 'en') })

