/**
 * Idiomas do site: português (endereços sem prefixo) e inglês (endereços em /en).
 *
 * As páginas trabalham sempre com o endereço em português (ex.: /produtos/planner);
 * localizePath() devolve o endereço equivalente no idioma da página (/en/shop/planner).
 * Assim os links escritos no painel (/portfolio#aquarela, /obras/limoes) funcionam nos dois idiomas.
 */
export type Locale = 'pt' | 'en'

export const LOCALES: Locale[] = ['pt', 'en']
export const DEFAULT_LOCALE: Locale = 'pt'

export const HTML_LANG: Record<Locale, string> = { pt: 'pt-BR', en: 'en' }
